#!/usr/bin/env python3
"""Generate helix/themes/rex-<id>.toml for every built-in Rex theme.

Reads the design tokens shipped inside Rex Beta.app, so rerun it after a Rex
update. Syntax roles come from vercel-dark; only the palette is generated.
"""
import colorsys
import json
import pathlib
import re
import sys

SRC = pathlib.Path(
    "/Applications/Rex Beta.app/Contents/Resources/"
    "SuperUI_SuperDesignTokens.bundle/Contents/Resources/themes.json"
)
OUT = pathlib.Path(__file__).resolve().parent.parent / "helix" / "themes"


def rgb(value, bg=None):
    """CSS token ("r g b", "rgb(r g b)", "rgb(r g b / a)") -> #rrggbb, alpha composited over bg."""
    nums = [float(n) for n in re.findall(r"[\d.]+", value)]
    r, g, b = nums[:3]
    if len(nums) == 4 and bg:
        a = nums[3]
        br, bgg, bb = (int(bg[i : i + 2], 16) for i in (1, 3, 5))
        r, g, b = (a * c + (1 - a) * k for c, k in ((r, br), (g, bgg), (b, bb)))
    return "#%02x%02x%02x" % tuple(round(c) for c in (r, g, b))


def hue(hex_):
    return colorsys.rgb_to_hsv(*(int(hex_[i : i + 2], 16) / 255 for i in (1, 3, 5)))[0] * 360


def near(a, b, deg=30):
    d = abs(hue(a) - hue(b)) % 360
    return min(d, 360 - d) < deg


def palette(t):
    v, s = t["cssVariables"], t["source"]
    ansi = s["ansi"]
    bg = rgb(v["--super-bg"])
    dark = t["appearance"] == "dark"
    accent = rgb(v["--super-accent-solid"])
    red, green, orange, blue, purple, cyan = ansi[1], ansi[2], ansi[3], ansi[4], ansi[5], ansi[6]
    # Keywords use the accent unless it would blend into types, strings or functions.
    keyword = accent if not any(near(accent, c) for c in (blue, green, purple)) else red
    text = rgb(v["--super-text"])
    return {
        "background": bg,
        "surface": rgb(v["--super-sidebar"]),
        "elevated_surface": rgb(v["--super-raised"]),
        "element_hover": rgb(v["--super-selected"], bg),
        "element_selected": rgb(v["--super-accent-container"]),
        "active_line": rgb(v["--super-hover"], bg),
        "highlighted_line": rgb(v["--super-info-container"]),
        "selection": s["selectionBackground"],
        "border": rgb(v["--super-border-strong"]),
        "focused_border": accent,
        "text": text,
        "text_bright": ansi[15] if dark else ansi[0],
        "text_muted": rgb(v["--super-text-secondary"]),
        "text_disabled": rgb(v["--super-text-tertiary"]),
        "editor_foreground": text,
        "icon_muted": rgb(v["--super-text-secondary"]),
        "line_number": rgb(v["--super-text-tertiary"]),
        "active_line_number": text,
        "invisible": rgb(v["--super-border"]),
        "wrap_guide": rgb(v["--super-border"]),
        "indent_guide": rgb(v["--super-border"]),
        "predictive": rgb(v["--super-text-tertiary"]),
        "accent": accent,
        "pink": keyword,
        "red": red,
        "green": green,
        "orange": orange,
        "blue": blue,
        "purple": purple,
        "cyan": cyan,
        "muted_blue": ansi[12],
        "comment": rgb(v["--super-text-tertiary"]),
        "syntax_punctuation": rgb(v["--super-text-secondary"]),
        "cursor": s["cursor"],
        "diagnostic_error": rgb(v["--super-danger"]),
        "diagnostic_warning": rgb(v["--super-warning"]),
        "diagnostic_info": rgb(v["--super-info"]),
        "diagnostic_hint": rgb(v["--super-success"]),
        "search_match": rgb(v["--super-warning-container"]),
    }


def main():
    themes = json.loads((pathlib.Path(sys.argv[1]) if len(sys.argv) > 1 else SRC).read_text())
    for t in themes:
        lines = [
            f'# rex-{t["id"]} — Rex "{t["name"]}" ({t["appearance"]}).',
            "# Generated by scripts/gen-rex-helix-themes.py; edit the script, not this file.",
            'inherits = "vercel-dark"',
            "",
            "[palette]",
        ]
        lines += [f'{k} = "{c}"' for k, c in palette(t).items()]
        (OUT / f'rex-{t["id"]}.toml').write_text("\n".join(lines) + "\n")
    print(f"wrote {len(themes)} themes to {OUT}")


if __name__ == "__main__":
    main()
